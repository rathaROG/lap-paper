from __future__ import annotations

import json
from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.transforms import blended_transform_factory

from paper_artifacts_common import STYLE, ENVS, DATA, TABLES, save, writecsv
from paper_artifacts_charts import RC, env_marker, env_key, ratio_axis

ENV_NAMES = tuple(row[0] for row in ENVS)
WIDTH = 6.46
PIPELINES = [(f"{sequence}_{source}_{tracker}", f"{label} · {detector}", tracker)
             for tracker in ("centroid", "sort")
             for sequence, label in (("mot16_04", "MOT16-04"), ("mot20_03", "MOT20-03"))
             for source, detector in (("gt", "GT"), ("rfdetr_nano", "RF-DETR"))]
API_KEYS = {"laprust": "jvrust", "lapcpp": "jvcpp", "lapjvh": "jvhybrid",
            "lapjv": "jvx_rowmap", "lapjvx": "jvx_indices", "lapjvxa": "jvx", "lapjvs": "jvs"}
API_LABELS = {"laprust": "JVRUST", "lapcpp": "JVCPP", "lapjvh": "JVHYBRID",
              "lapjv": "JVX row-map", "lapjvx": "JVX indices", "lapjvxa": "JVX pairs", "lapjvs": "JVS"}
GROUPS = [("Native APIs", ("laprust", "lapcpp", "lapjvh"), "jvrust"),
          ("JVX / JVS APIs", ("lapjv", "lapjvx", "lapjvxa", "lapjvs"), "jvx")]
LSAPE_CONTRASTS = [("original_over_padded", "O/P", "Total change · frozen primary", "P"),
                   ("original_over_one_sided", "O/U", "One-sided formulation", "U"),
                   ("one_sided_over_padded", "U/P", "Specialization, same buffer", "P"),
                   ("padded_over_compact", "P/T", "Compact layout", "T"),
                   ("scan_over_compact", "S/T", "Rejection-slack caching", "T")]
LSAPE_FAMILIES = [("A", "Square"), ("B", "5:4 uniform"), ("C", "5:4 congested"),
                  ("D", "4:1"), ("E", "Extreme"), ("F", "Threshold ties")]


def write_tex(path, lines):
    Path(path).write_text("% Generated by paper_artifacts_support_figures.py.\n" +
                          "\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def classes(values):
    values = list(values)
    win, loss = sum(v > 1.03 for v in values), sum(v < .97 for v in values)
    return dict(win=win, tie=len(values)-win-loss, loss=loss)


def handles(methods):
    return [Line2D([], [], **env_marker("L311", STYLE[m]["color"], 3.5, STYLE[m]["marker"]),
                   label=STYLE[m]["label"]) for m in methods]


def app_dumbbell(slopes):
    """Connect the nearest measured range bounds; no synthetic centre statistic."""
    envelopes = []
    with plt.rc_context(RC):
        fig, ax = plt.subplots(figsize=(WIDTH, 3.6))
        for i, (case, _, tracker) in enumerate(PIPELINES):
            for g, (label, apis, method) in enumerate(GROUPS):
                rows = [r for r in slopes if r['case'] == case and r['solver'] in apis]
                assert len(rows) == 4*len(apis)
                rlo, rhi = min(r['replay_ratio'] for r in rows), max(r['replay_ratio'] for r in rows)
                ulo, uhi = min(r['update_ratio'] for r in rows), max(r['update_ratio'] for r in rows)
                assert rhi < ulo or uhi < rlo, 'Range arrows require disjoint envelopes'
                start, end = (rlo, uhi) if rlo > uhi else (rhi, ulo)
                y = i + (g-.5)*.34
                color = STYLE[method]['color']
                ax.annotate('', xy=(end, y), xytext=(start, y),
                            arrowprops=dict(arrowstyle='-|>', color=color, lw=.8,
                                            mutation_scale=6, shrinkA=1, shrinkB=1))
                ax.plot([rlo, rhi], [y, y], color=color, lw=4, alpha=.32, solid_capstyle='butt')
                ax.plot([ulo, uhi], [y, y], color=color, lw=4, solid_capstyle='butt')
                envelopes.append(dict(case=case, tracker=tracker, group=label, observations=len(rows),
                    apis=list(apis), environments=list(ENV_NAMES), replay_min=rlo, replay_max=rhi,
                    update_min=ulo, update_max=uhi, arrow_start=start, arrow_end=end,
                    arrow_definition='nearest disjoint range bounds; no averaged or pooled central value'))
        ratio_axis(ax, .6, 3.6)
        ax.set_yticks(range(8), [label for _, label, _ in PIPELINES])
        ax.set_ylim(7.55, -.55)
        ax.axhline(3.5, color='#bbbbbb', lw=.6)
        ax.text(3.5, .1, 'Centroid', ha='right', va='center', fontsize=7.5, fontweight='bold')
        ax.text(3.5, 4.1, 'SORT', ha='right', va='center', fontsize=7.5, fontweight='bold')
        ax.set_xlabel('SciPy time / method time (log)')
        ax.spines['left'].set_visible(False); ax.tick_params(axis='y', length=0)
        fig.legend(handles=[Line2D([], [], color=STYLE[m]['color'], lw=3, label=label)
                            for label, _, m in GROUPS], ncol=2, frameon=False,
                   loc='upper center', bbox_to_anchor=(.59,.995), fontsize=7.5)
        fig.text(.59,.09,'Pale: float32 replay range  →  solid: tracker.update range',
                 ha='center', fontsize=7)
        fig.subplots_adjust(left=.19,right=.985,top=.86,bottom=.23)
        save(fig, 'F7_applications_dumbbell'); plt.close(fig)
    writecsv('F7_application_envelopes.csv',envelopes)
    writecsv('F7_applications_api.csv',slopes)
    app_table(slopes)
    return envelopes


def app_table(slopes):
    lookup = {(r['environment'],r['case'],r['solver']):r for r in slopes}
    lines = [r'\section*{Application API ratios}',
             r'Each cell gives float32 assignment replay / tracker.update speed ratios, each relative to SciPy within the same environment. Values are displayed to three decimals; classifications use unrounded values. Absolute times and round estimates remain in S4 exports.']
    for number,(case,label,tracker) in enumerate(PIPELINES):
        if number and number%2==0: lines.append(r'\clearpage')
        lines += [r'\subsection*{'+label.replace(' · ',' / ')+' / '+tracker.capitalize()+'}',
                  r'\begin{center}\small',r'\begin{tabular}{lrrrr}',r'\toprule',
                  r'API & L311 & L314 & W311 & W314 \\',r'\midrule']
        for api in API_KEYS:
            cells = [f"{lookup[env,case,api]['replay_ratio']:.3f} / {lookup[env,case,api]['update_ratio']:.3f}" for env in ENV_NAMES]
            lines.append(API_LABELS[api]+' & '+' & '.join(cells)+r' \\')
        lines += [r'\bottomrule',r'\end{tabular}',r'\end{center}']
    write_tex(TABLES/'S_applications_api.tex',lines)


def lsape_strip(plotted):
    summary, family_rows = {}, []
    with plt.rc_context(RC):
        fig, ax = plt.subplots(figsize=(WIDTH,3.1))
        for k,env in enumerate(('W311','W314')):
            summary[env]={}
            for j,(contrast,label,title,denominator) in enumerate(LSAPE_CONTRASTS):
                rows=sorted((r for r in plotted if r['environment']==env and r['comparison']==contrast),key=lambda r:r['case'])
                values=[float(r['median_estimate']) for r in rows]
                assert len(values)==67
                counted=classes(values);summary[env][label]=dict(min=min(values),max=max(values),**counted)
                ybase=j+(k-.5)*.32
                color=STYLE[denominator]['color']
                for i,value in enumerate(values):
                    jitter=((i*37)%9-4)*.021
                    ax.plot([value],[ybase+jitter],marker=STYLE[denominator]['marker'],ms=2.5,
                            mec=color,mew=.55,mfc=color if env=='W311' else 'white',ls='none',alpha=.8)
                ax.text(1.025,ybase,f"{env}: {counted['win']}/{counted['tie']}/{counted['loss']}",
                        transform=blended_transform_factory(ax.transAxes,ax.transData),ha='left',va='center',fontsize=6.8)
                for block,family in LSAPE_FAMILIES:
                    vals=[float(r['median_estimate']) for r in rows if r['block']==block]
                    family_rows.append(dict(environment=env,block=block,family=family,comparison=contrast,
                                            label=label,cases=len(vals),**classes(vals)))
        ratio_axis(ax,.35,3.5)
        ax.set_xticks([.5,1,2,3])
        ax.set_yticks(range(5),[label+'  '+title for _,label,title,_ in LSAPE_CONTRASTS])
        ax.set_ylim(4.55,-.55);ax.tick_params(axis='y',length=0,labelsize=7)
        ax.spines['left'].set_visible(False)
        ax.set_xlabel('Numerator time / denominator time (log; >1: denominator faster)',fontsize=7)
        ax.text(1.025,1.04,'Wins / ties / losses',transform=ax.transAxes,fontsize=6.8,ha='left')
        fig.legend(handles=[Line2D([],[],marker='o',ms=3.5,ls='none',mfc=fill,mec='#444444',
                                   label=env+' '+desc) for env,fill,desc in
                            [('W311','#444444','filled'),('W314','white','open')]],
                   loc='upper center',bbox_to_anchor=(.58,.995),ncol=2,fontsize=7)
        fig.subplots_adjust(left=.34,right=.81,top=.82,bottom=.20)
        save(fig,'F8_lsape_strip');plt.close(fig)
    writecsv('F8_lsape_values.csv',plotted);writecsv('F8_lsape_family_counts.csv',family_rows)
    lines=[r'\begin{tabular}{llrrrrrr}',r'\toprule',
           r'Family & Env. & $n$ & O/P & O/U & U/P & P/T & S/T \\',r'\midrule']
    for block,family in LSAPE_FAMILIES:
        for env in ('W311','W314'):
            rows=[next(r for r in family_rows if r['block']==block and r['environment']==env and r['comparison']==contrast)
                  for contrast,*_ in LSAPE_CONTRASTS]
            cells=[f"{r['win']}/{r['tie']}/{r['loss']}" for r in rows]
            lines.append(f"{family} & {env} & {rows[0]['cases']} & "+' & '.join(cells)+r' \\')
        lines.append(r'\addlinespace')
    lines += [r'\bottomrule',r'\end{tabular}']
    write_tex(TABLES/'S_lsape_family_counts.tex',lines)
    return summary,family_rows,[]


def batch_dots(data):
    first=data['L311'];cases={c['id']:c for c in first['manifest']['cases']}
    standard=['batch:batch64x64x80','batch:batch16x128x160_optional','batch:batch1024x8x10']
    workspace=sorted({r['case_id'] for r in first['summary']['batch_contrasts'] if r['contrast']=='solver_state_lifetime'},
                     key=lambda cid:(cases[cid]['rows']>cases[cid]['cols'],cases[cid]['rows']*cases[cid]['cols'],cid))
    records=[]
    def draw(ax,selected,series,figure):
        for i,cid in enumerate(selected):
            for j,(contrast,prefix,method,invert,workers) in enumerate(series):
                for ei,(env,d) in enumerate(data.items()):
                    matches=[r for r in d['summary']['batch_contrasts'] if r['case_id']==cid and r['contrast']==contrast
                             and r['method'].startswith(prefix) and (workers is None or r['workers']==workers)]
                    assert len(matches)==1,(cid,env,contrast,prefix,len(matches))
                    row=matches[0];value=1/row['ratio'] if invert else row['ratio']
                    if row['pairing']=='same_paired_attempt':
                        assert row['attempt_id']==row['reference_attempt_id']
                    ax.plot([value],[i+(j-(len(series)-1)/2)*.18+(ei-1.5)*.023],
                            **env_marker(env,STYLE[method]['color'],3.0,STYLE[method]['marker']))
                    records.append(dict(figure=figure,environment=env,case_id=cid,contrast=contrast,
                        method=row['method'],reference=row['reference'],ratio=value,stored_ratio=row['ratio'],
                        ratio_definition='method_seconds / reference_seconds' if invert else 'reference_seconds / method_seconds',
                        seconds=row['seconds'],reference_seconds=row['reference_seconds'],attempt_id=row['attempt_id'],
                        reference_attempt_id=row['reference_attempt_id'],pairing=row['pairing'],input_hashes=row['input_hashes'],
                        source=(d['root']/'campaign-summary.json').relative_to(d['root'].parents[3]).as_posix()))
        ax.set_ylim(len(selected)-.55,-.55);ax.spines['left'].set_visible(False);ax.tick_params(axis='y',length=0)
    labels=lambda ids:[f"{cases[c]['metadata']['batch_size']}×{cases[c]['rows']}×{cases[c]['cols']} "+('R' if cases[c]['objective']=='required' else 'O') for c in ids]
    native=['jvrust','jvcpp'];standard_methods=native+['jvhybrid','jvx']
    top=[('Loop → batch, one worker',[('batch_overhead','batch:jvrust:','jvrust',False,1)]),
         ('Batch API: one → four workers',[('worker_count','batch:'+m+':',m,False,4) for m in standard_methods])]
    bottom=[('Workspace: one → four workers','workspace_worker_count','w0',False),
            ('Scratch reuse, four workers','solver_state_lifetime','w1',True),
            ('Orientation reuse, four workers','orientation_buffer_lifetime','w2',True)]
    with plt.rc_context(RC):
        fig=plt.figure(figsize=(WIDTH,6.25))
        upper=fig.add_gridspec(1,2,left=.16,right=.985,top=.82,bottom=.65,wspace=.13)
        lower=fig.add_gridspec(1,3,left=.16,right=.985,top=.48,bottom=.10,wspace=.13)
        for j,(title,series) in enumerate(top):
            ax=fig.add_subplot(upper[0,j]);draw(ax,standard,series,'F6_batch_dots')
            ratio_axis(ax,.3,4);ax.set_yticks(range(3),labels(standard) if j==0 else [])
            ax.set_title(title,loc='left',pad=28,fontsize=8)
            ax.legend(handles=handles(['jvrust'] if j==0 else standard_methods),loc='lower left',bbox_to_anchor=(0,1.01),
                      ncol=1 if j==0 else 2,fontsize=6.5,columnspacing=.7,handletextpad=.3,borderaxespad=0)
        for j,(title,contrast,level,invert) in enumerate(bottom):
            ax=fig.add_subplot(lower[0,j]);series=[(contrast,f'workspace:{lang}:{level}:',method,invert,4)
                                                for lang,method in [('rust','jvrust'),('cpp','jvcpp')]]
            draw(ax,workspace,series,'F6_batch_dots');ratio_axis(ax,.5,4)
            ax.set_yticks(range(len(workspace)),labels(workspace) if j==0 else [])
            ax.set_title(title.replace(', ','\n'),loc='left',pad=23,fontsize=7.5)
            ax.legend(handles=handles(native),loc='lower left',bbox_to_anchor=(0,1.015),ncol=2,fontsize=6.2,
                      columnspacing=.5,handletextpad=.2,borderaxespad=0)
        env_key(fig,.57,.995,'marker')
        fig.text(.57,.935,'Standard batch calls',ha='center',fontsize=8.5,fontweight='bold')
        fig.text(.57,.58,'Reusable workspace calls',ha='center',fontsize=8.5,fontweight='bold')
        fig.text(.57,.027,'Ratio (log; >1 favours batching, four workers or retained state)',ha='center',fontsize=7)
        save(fig,'F6_batch_dots');plt.close(fig)
    with plt.rc_context(RC):
        fig,axes=plt.subplots(1,2,figsize=(WIDTH,5.5),gridspec_kw={'wspace':.14})
        for j,(contrast,level,title) in enumerate([('solver_state_lifetime','w1','Scratch reuse: W1 / W0'),
                                                 ('orientation_buffer_lifetime','w2','Orientation reuse: W2 / W1')]):
            ax=axes[j];series=[(contrast,f'workspace:{lang}:{level}:',method,True,1)
                              for lang,method in [('rust','jvrust'),('cpp','jvcpp')]]
            draw(ax,workspace,series,'S_batch_reuse_one_worker');ratio_axis(ax,.5,4)
            ax.set_yticks(range(len(workspace)),labels(workspace) if j==0 else [])
            ax.set_title(title,loc='left',pad=24,fontsize=8)
            ax.legend(handles=handles(native),loc='lower left',bbox_to_anchor=(0,1.01),ncol=2,fontsize=7,borderaxespad=0)
            ax.set_xlabel('Recreate / retain time (log)')
        env_key(fig,.57,.995,'marker');fig.subplots_adjust(left=.18,right=.985,top=.82,bottom=.11)
        save(fig,'S_batch_reuse_one_worker');plt.close(fig)
    assert sum(r['figure']=='F6_batch_dots' for r in records)==396
    assert sum(r['figure']=='S_batch_reuse_one_worker' for r in records)==224
    writecsv('F6_batch_dot_values.csv',records)
    return dict(main_points=396,supplemental_points=224,workspace_cases=14,standard_cases=3,
                ratio_direction='greater than one favours batching, four workers or retained state')


def orientation_dots(data):
    shapes=[(1000,2000,'o'),(2000,3000,'s'),(4000,5000,'D'),(64,4096,'^'),(64,8192,'v'),(64,16384,'P')]
    groups=[('required',['jvrust','jvhybrid','jvcpp','jvx','jvs','scipy']),
            ('optional',['jvrust','jvcpp','jvx','scipy:capped','scipy:dummies','scipy:diagonal_dummies','scipy:square','sparse:csgraph','sparse:lapmod'])]
    records=[];missing=[]
    with plt.rc_context(RC):
        fig,axes=plt.subplots(1,2,figsize=(WIDTH,4.8),gridspec_kw={'wspace':.65})
        for ax,(objective,methods) in zip(axes,groups):
            for ei,(env,d) in enumerate(data.items()):
                cases=[c for c in d['manifest']['cases'] if c['kind']=='single' and c['objective']==objective
                       and c['family'] in ('large_rectangle','extreme_rectangle')]
                estimates={(r['case_id'],r['method']):r for r in d['summary']['estimates'] if r['status']=='complete'}
                for si,(r,c,marker) in enumerate(shapes):
                    wide=next(x for x in cases if (x['rows'],x['cols'])==(r,c) and not x['transpose'])
                    tall=next(x for x in cases if (x['rows'],x['cols'])==(c,r) and x['transpose'])
                    for mi,method in enumerate(methods):
                        if (wide['id'],method) not in estimates or (tall['id'],method) not in estimates:
                            missing.append(dict(environment=env,objective=objective,method=method,shape=f'{r}x{c}',status='not_planned'))
                            continue
                        a,b=estimates[tall['id'],method],estimates[wide['id'],method];ratio=a['seconds']/b['seconds']
                        ax.plot([ratio],[mi+(si-2.5)*.105+(ei-1.5)*.018],
                                **env_marker(env,STYLE[method]['color'],3.2,marker))
                        records.append(dict(environment=env,objective=objective,method=method,shape=f'{r}x{c}',
                            shape_marker=marker,wide_case_id=wide['id'],tall_case_id=tall['id'],tall_over_wide=ratio,
                            wide_seconds=b['seconds'],tall_seconds=a['seconds'],wide_attempt=b['attempt_id'],tall_attempt=a['attempt_id'],
                            input_group=wide['input_group'],pairing='different_case_attempts_shared_input_group',
                            source=(d['root']/'campaign-summary.json').relative_to(d['root'].parents[3]).as_posix()))
            ratio_axis(ax,.7,100);ax.set_ylim(len(methods)-.55,-.55)
            labels=[]
            for method in methods:
                label=STYLE[method]['label'].replace(' columns','').replace(' required','').replace('SciPy diagonal dummies','Diagonal dummy')
                if objective=='required' and method in ('jvx','jvs'):label+=' †'
                if objective=='optional' and method in ('jvx','scipy:square'):label+=' ‡'
                labels.append(label)
            ax.set_yticks(range(len(methods)),labels)
            for tick,method in zip(ax.get_yticklabels(),methods):tick.set_color(STYLE[method]['color'])
            ax.spines['left'].set_visible(False);ax.tick_params(axis='y',length=0)
            ax.set_title(objective.capitalize()+' assignment',loc='left',fontsize=8.5)
            ax.set_xlabel('Tall time / wide time (log)',fontsize=7)
        legend=[Line2D([],[],marker=m,ms=3.8,mfc='#555555',mec='#555555',ls='none',label=f'{r}×{c}')
                for r,c,m in [shapes[i] for i in (0,3,1,4,2,5)]]
        fig.legend(handles=legend,loc='upper center',bbox_to_anchor=(.5,.995),ncol=3,fontsize=7,columnspacing=1.5)
        env_key(fig,.52,.90,'marker')
        fig.text(.51,.072,'† Not planned: 4000×5000, 64×8192, 64×16384.  ‡ Only 1000×2000 planned.',ha='center',fontsize=6.5)
        fig.text(.51,.026,'>1: tall is slower. Shape markers name the wide member of each transpose pair.',ha='center',fontsize=6.5)
        fig.subplots_adjust(left=.14,right=.96,top=.76,bottom=.19)
        save(fig,'F9_orientation_dots');plt.close(fig)
    assert len(records)==296 and len(missing)==64
    writecsv('F9_orientation_dot_values.csv',records);writecsv('F9_orientation_not_planned.csv',missing)
    return dict(points=len(records),points_per_environment=74,complete_export_pairs_per_environment=74,
                not_planned=len(missing),shapes=[f'{r}x{c}' for r,c,_ in shapes])


def generate_behavior(repo,data):
    result=dict(batch=batch_dots(data),orientation=orientation_dots(data),
        atlas_figures=[dict(name='S_batch_reuse_one_worker',title='Workspace reuse with one worker',
            scope='Each marker is one workload, method and environment. Recreate/retain ratios above one favour retaining state. The main batch figure shows four-worker reuse.')],
        atlas_tables=[dict(path='S_applications_api.tex',title='Application APIs',scope='All per-API replay and update ratios, with environments separate.')])
    (DATA/'support_atlas.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8',newline='\n')
    return result
