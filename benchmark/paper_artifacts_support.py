def generate_support(repo: Path) -> dict:
    repo = Path(repo).resolve()
    image_dir, table_dir, export_dir = repo / "latex/images/current", repo / "latex/generated", repo / "benchmark/paper-artifacts"
    for directory in (image_dir, table_dir, export_dir): directory.mkdir(parents=True, exist_ok=True)
    data = {}
    for env, run in RUNS.items():
        root = repo / "benchmark/runs" / run / "paper-run-light"
        data[env] = dict(root=root, summary=read_json(root / "campaign-summary.json"),
                         manifest=read_json(root / "campaign-session/manifest.json"))
    style = read_json(repo / "benchmark/paper_artifact_panels/style_mapping.json")
    result = dict(protocol=protocol_tables(repo, data, table_dir, export_dir))
    for key, function, args in [
            ("applications", applications, (repo, data, style, image_dir, table_dir, export_dir)),
            ("lsape", lsape, (repo, data, style, image_dir, export_dir)),
            ("memory", memory, (repo, data, style, image_dir, table_dir, export_dir))]:
        with plt.rc_context(plt.rcParamsDefault):
            style_settings()
            result[key] = function(*args)
    from paper_artifacts_support_figures import generate_behavior
    with plt.rc_context(plt.rcParamsDefault):
        result["behavior"] = generate_behavior(repo, data)
    result["artifacts"] = {
        "F6": "latex/images/current/F6_batch_dots.pdf", "F7": "latex/images/current/F7_applications_dumbbell.pdf",
        "F8": "latex/images/current/F8_lsape_strip.pdf", "F9": "latex/images/current/F9_orientation_dots.pdf",
        "A4": "latex/images/current/A4_memory_visibility.pdf", "T1": "latex/generated/T1_protocol.tex",
        "T2": "latex/generated/T2_methods.tex", "T4": "latex/generated/T4_memory.tex",
        "application_workloads": "latex/generated/A_application_workloads.tex",
        "application_accuracy": "latex/generated/A_application_accuracy.tex"}
    result["generator"] = "benchmark/paper_artifacts_support.py"
    result["primary_roots"] = {env:value["root"].relative_to(repo).as_posix() for env,value in data.items()}
    sources = []
    for env, value in data.items():
        root = value["root"]
        files = [root / name for name in ("campaign-summary.json", "campaign-session/manifest.json",
            "campaign-session/environment.json", "status.json", "application-session/protocol.json",
            "application-session/summary.json", "application-session/tracking_summary.csv", "application-session/replay_summary.csv")]
        files.extend(sorted((root / "application-session/profiles").glob("*__scipy.json")))
        files.append(root / "application-session/tracking_samples.json")
        files.extend(sorted((root / "application-session/replay").glob("*.json")))
        if env.startswith("W"):
            files.extend([root / "lsape-summary/all_cases.csv", root / "lsape-summary/summary.json"])
            files.extend(root / f"lsape-session-{index}/report.json" for index in (1, 2, 3))
        sources.extend(dict(environment=env, source_file=path.relative_to(repo).as_posix(),
                            sha256=hashlib.sha256(path.read_bytes()).hexdigest()) for path in files)
    dump_csv(export_dir / "support_source_inventory.csv", sources)
    (export_dir / "support_summary.json").write_text(json.dumps(result, indent=2)+"\n", encoding="utf-8")
    return result


