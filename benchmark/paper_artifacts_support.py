    fig.subplots_adjust(left=.07, right=.995, top=.85, bottom=.27, wspace=.12)
    save_figure(fig, image_dir, "A4_memory_visibility")
    return dict(per_environment=summaries, endpoint_rows=endpoint_rows,
                source="campaign-summary.json.memory.conditions[].trials[]",
                interpretation="Additional high-water increment is not total allocation; final RSS change is not peak memory.")


