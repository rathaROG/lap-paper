def read_json(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def dump_csv(path, rows):
    rows = list(rows)
    fields = list(dict.fromkeys(key for row in rows for key in row))
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow({key: json.dumps(value, sort_keys=True, separators=(",", ":"))
                             if isinstance(value, (dict, list)) else value for key, value in row.items()})


def write_tex(path, lines):
    lines = [line + chr(92) if line.endswith(chr(92)) and not line.endswith(chr(92)*2) else line for line in lines]
    path.write_text("% Generated by benchmark/paper_artifacts_support.py; do not edit.\n" +
                    "\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def classify(ratio):
    return "win" if ratio > 1.03 else "loss" if ratio < .97 else "tie"


def counts(values):
    values = list(values)
    return {key: sum(classify(value) == key for value in values) for key in ("win", "tie", "loss")}


def label_case(case):
    return case.replace("mot16_04", "M16").replace("mot20_03", "M20").replace("rfdetr_nano", "RF").replace("centroid", "C").replace("sort", "S").replace("_", " / ")


